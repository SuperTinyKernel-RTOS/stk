"""Generate stk_revision.h (build metadata: commit count + git hash).

Usage: gen_revision.py --output <path/stk_revision.h> [--root <repo-root>]

Never fails the build: if git or history is unavailable (tarball, shallow
clone, vendored copy inside another repository), it falls back to
revision 0 / hash "unknown".

The output file is rewritten only when its content changes, so an unchanged
revision does not trigger a rebuild of every file that includes stk_version.h.
"""

import argparse
import subprocess
import sys
from pathlib import Path

HEADER_TEMPLATE = """\
/*
 * SuperTinyKernel(TM) RTOS: Lightweight High-Performance Deterministic C++ RTOS for Embedded Systems.
 *
 * Source: https://github.com/SuperTinyKernel-RTOS
 *
 * Copyright (c) 2022-2026 Neutron Code Limited <stk@neutroncode.com>. All Rights Reserved.
 * License: MIT License, see LICENSE for a full text.
 */

#ifndef STK_REVISION_H_
#define STK_REVISION_H_

// WARNING: Generated by gen_revision.py, do not edit!

#define STK_VERSION_REVISION {revision}
#define STK_VERSION_GIT_HASH "{git_hash}"

#endif /* STK_REVISION_H_ */
"""


def git(root: Path, *args: str):
    """Run git in root, return stripped stdout or None on any failure."""
    try:
        result = subprocess.run(
            ["git", "-C", str(root), *args],
            capture_output=True, text=True, check=True, timeout=30,
        )
        return result.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None


def collect(root: Path):
    """Return (revision, git_hash) for the repository at root."""
    # Only trust git if root IS the repository top level. Otherwise STK is a
    # vendored folder inside someone else's repository and the numbers
    # would describe the wrong project.
    toplevel = git(root, "rev-parse", "--show-toplevel")
    if toplevel is None or Path(toplevel).resolve() != root.resolve():
        return 0, "unknown"

    if git(root, "rev-parse", "--is-shallow-repository") == "true":
        print("gen_revision: shallow clone, commit count is unreliable "
              "(fetch full history)", file=sys.stderr)

    count = git(root, "rev-list", "--count", "HEAD")
    short = git(root, "rev-parse", "--short=8", "HEAD")
    if count is None or short is None or not count.isdigit():
        return 0, "unknown"

    # Tracked-file changes only; untracked files (incl. build dirs) are ignored.
    status = git(root, "status", "--porcelain", "--untracked-files=no")
    if status:
        short += "-dirty"

    return int(count), short


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", required=True, type=Path,
                        help="path of the header to generate")
    parser.add_argument("--root", type=Path, default=Path.cwd(),
                        help="git repository root (default: current directory)")
    args = parser.parse_args()

    revision, git_hash = collect(args.root)
    content = HEADER_TEMPLATE.format(revision=revision, git_hash=git_hash)

    try:
        if args.output.read_text() == content:
            return 0
    except OSError:
        pass

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
