static bool InitNetwork()
{
    // Must run from inside the task, not from RunExample() before kernel.Start() -
    // see the file header for why (cyw43_arch_init()'s async_context_stk needs a
    // running STK task to call stk::GetTid() from).
    if (cyw43_arch_init())
    {
        printf("failed to initialise\n");
        return false;
    }

    // Initialize PSA Crypto engine (Required for Mbed TLS 4)
    psa_status_t status = psa_crypto_init();
    if (status != PSA_SUCCESS)
    {
        printf("failed to initialise PSA crypto: %d\n", (int)status);
        cyw43_arch_deinit();
        return false;
    }

    cyw43_arch_enable_sta_mode();

    return true;
}

static void ShutdownNetwork()
{
#if LWIP_MDNS_RESPONDER
    mdns_resp_remove_netif(&cyw43_state.netif[CYW43_ITF_STA]);
    udp_remove(get_mdns_pcb());
    // KNOWN ISSUE: this doesn't decrement netif_client_id in netif.c, so a later
    // mdns_resp_add_netif() will assert in netif_alloc_client_data_id() on reinit.
#endif
    cyw43_arch_disable_sta_mode();
    cyw43_arch_deinit();
}

static void InitServer()
{
    char hostname[sizeof(CYW43_HOST_NAME) + 4];
    memcpy(&hostname[0], CYW43_HOST_NAME, sizeof(CYW43_HOST_NAME) - 1);
    get_mac_ascii(CYW43_HAL_MAC_WLAN0, 8, 4, &hostname[sizeof(CYW43_HOST_NAME) - 1]);
    hostname[sizeof(hostname) - 1] = '\0';
    netif_set_hostname(&cyw43_state.netif[CYW43_ITF_STA], hostname);

#if LWIP_MDNS_RESPONDER
    // Set up the mDNS responder.
    cyw43_arch_lwip_begin();
    mdns_resp_init();
    printf("mdns host name %s.local\n", hostname);
#if LWIP_VERSION_MAJOR >= 2 && LWIP_VERSION_MINOR >= 2
    mdns_resp_add_netif(&cyw43_state.netif[CYW43_ITF_STA], hostname);
    mdns_resp_add_service(&cyw43_state.netif[CYW43_ITF_STA], "pico_httpd", "_http", DNSSD_PROTO_TCP, 80, srv_txt, NULL);
#else
    mdns_resp_add_netif(&cyw43_state.netif[CYW43_ITF_STA], hostname, 60);
    mdns_resp_add_service(&cyw43_state.netif[CYW43_ITF_STA], "pico_httpd", "_http", DNSSD_PROTO_TCP, 80, 60, srv_txt, NULL);
#endif
    cyw43_arch_lwip_end();
#endif
    // Set up the HTTP server. CGI/SSI handlers are global state shared by
    // both the plain-HTTP and HTTPS listeners below, so only need setting once.
    cyw43_arch_lwip_begin();
    httpd_init();
    http_set_cgi_handlers(CGI_HANDLERS, LWIP_ARRAYSIZE(CGI_HANDLERS));
    http_set_ssi_handler(ssi_example_ssi_handler, SSI_TAGS, LWIP_ARRAYSIZE(SSI_TAGS));

    // Set up HTTPS on top of the same httpd instance. Uses a self-signed
    // cert (see certs_der.h / generate_cert.sh) - browsers will show a
    // "not private" warning on first visit since it's not CA-signed; that's
    // expected for a self-generated cert and can be bypassed/accepted or
    // the cert can be installed as trusted on the client.
    s_TlsConfig = altcp_tls_create_config_server_privkey_cert(
        s_TlsKey, sizeof(s_TlsKey),
        NULL, 0,   /* private key is not password-protected */
        s_TlsCert, sizeof(s_TlsCert));
    if (s_TlsConfig == NULL)
    {
        printf("Failed to create TLS config - HTTPS disabled, HTTP still available\n");
    }
    else
    {
        httpd_inits(s_TlsConfig);
        printf("HTTPS server listening on port %d\n", HTTPD_SERVER_PORT_HTTPS);
    }
    cyw43_arch_lwip_end();
}

static bool ConnectWiFi()
{
    printf("Connecting to WiFi...\n");
    if (cyw43_arch_wifi_connect_timeout_ms(WIFI_SSID, WIFI_PASSWORD, CYW43_AUTH_WPA2_AES_PSK, 30000))
    {
        printf("failed to connect.\n");
        return false;
    }
    else
    {
        printf("Connected.\n");
    }
    printf("\nReady, running httpd at %s\n", ip4addr_ntoa(netif_ip4_addr(netif_list)));

    // Record the connect time for the "uptime" SSI tag.
    s_ConnectedTime = get_absolute_time();

    return true;
}

// Owns Wi-Fi connect and httpd/mDNS server setup, driven by control-flag events
// rather than the original's while(true) superloop. It doesn't drive the cyw43
// driver itself - async_context_stk's own worker task (spun up inside
// cyw43_arch_init()) does that - so this task's loop just needs to stay alive
// and react to flags after setup.
class WifiHttpdTask : public stk::Task<TASK_STACK_SIZE, stk::ACCESS_PRIVILEGED>
{
private:
    void Run() override
    {
        bool running = true;
        while (running)
        {
            const uint32_t raised = s_ControlFlags.Wait(FLAG_CONNECT_WIFI | FLAG_LED_UPDATE | FLAG_INIT_NET | FLAG_SHUTDOWN_NET, stk::sync::EventFlags::OPT_WAIT_ANY, stk::WAIT_INFINITE);
            if (stk::sync::EventFlags::IsError(raised))
            {
                continue;
            }

            if (raised & FLAG_LED_UPDATE)
            {
                cyw43_arch_lwip_begin();
                cyw43_gpio_set(&cyw43_state, 0, s_LedOn);
                cyw43_arch_lwip_end();
            }
            if (raised & FLAG_CONNECT_WIFI)
            {
                if (!ConnectWiFi())
                {
                    RequestConnectWiFi();
                }
            }
            if (raised & FLAG_INIT_NET)
            {
                if (InitNetwork())
                {
                    InitServer();
                    RequestConnectWiFi();
                }
                else
                {
                    RequestInitNetwork();
                }
            }
            if (raised & FLAG_SHUTDOWN_NET)
            {
                ShutdownNetwork();
                RequestInitNetwork();
            }
        }
    }
};

void RunExample()
{
    using namespace stk;

    // Bring up stdio for logging.
    stdio_init_all();

    // Enable dynamic task registration and inter-task sync, plus tickless idle
    // where the platform supports it.
    static constexpr uint8_t KernelMode = KERNEL_DYNAMIC | KERNEL_SYNC | (STK_TICKLESS_IDLE ? KERNEL_TICKLESS : 0);

    // Task budget: WifiHttpdTask + TimerHost + async_context_stk's worker tasks +
    // lwIP's own sys_thread_new()-spawned tcpip thread (sized by
    // LWIP_STK_THREAD_POOL_SIZE). Note: LWIP_STK_NETCONN_SEM_MAX_THREADS is NOT a
    // task count - it sizes sys_arch's TId-keyed side-table for
    // LWIP_NETCONN_SEM_PER_THREAD and has no bearing on kernel.AddTask() capacity.
    static constexpr size_t tasks_count = 1U + stk::time::TimerHost::TASK_COUNT + ASYNC_CONTEXT_STK_TASKS + LWIP_STK_THREAD_POOL_SIZE;

    // Allocate the scheduling kernel with priority-based scheduling (SwitchStrategyFP32).
    static Kernel<KernelMode, tasks_count, SwitchStrategyFP32, PlatformDefault> kernel;
    static stk::time::TimerHost timer_host;
    static WifiHttpdTask task;

    kernel.Initialize();

    timer_host.Initialize(&kernel, stk::ACCESS_USER);

    // Register the task with the kernel.
    kernel.AddTask(&task);

    // init mbedTLS threading
    stk_mbedtls_threading_init();

    // Wire the kernel into lwIP's sys_arch port - must happen before lwip_init().
    sys_arch_set_kernel(&kernel);

    // Wire the kernel and timer host into the cyw43 port - must happen before cyw43_arch_init().
    cyw43_arch_stk_preinit(&kernel, &timer_host);

    // Kick off network init once the task starts running; safe to request before kernel.Start().
    RequestInitNetwork();

    // Start the scheduler - this runs the registered task and blocks here permanently.
    kernel.Start();

    // Unreachable: kernel.Start() never returns.
    STK_ASSERT(false);
}

// mbedTLS specific:

extern "C" int __mbedtls_platform_get_entropy(psa_driver_get_entropy_flags_t flags, size_t *estimate_bits,
    unsigned char *output, size_t output_size)
{
    /* We don't implement any special flags */
    if (flags != 0)
    {
        return PSA_ERROR_NOT_SUPPORTED;
    }

    if (output == NULL || estimate_bits == NULL)
    {
        return PSA_ERROR_INVALID_ARGUMENT;
    }

    /* Sample physical noise bits from ROSC */
    for (size_t i = 0; i < output_size; i++)
    {
        uint8_t random_byte = 0;
        for (int b = 0; b < 8; b++)
        {
            random_byte = (random_byte << 1) | (rosc_hw->randombit & 1);
        }
        output[i] = random_byte;
    }

    /* Set the estimated entropy bits gathered (8 bits per byte) */
    *estimate_bits = 8 * output_size;

    return 0; // Success
}

