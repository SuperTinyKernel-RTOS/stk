    case MBEDTLS_TLS1_3_SIG_ECDSA_SECP384R1_SHA384: return "ecdsa_secp384r1_sha384";
    case MBEDTLS_TLS1_3_SIG_ECDSA_SECP521R1_SHA512: return "ecdsa_secp521r1_sha512";

    /* RSA-PSS */
    case MBEDTLS_TLS1_3_SIG_RSA_PSS_RSAE_SHA256:  return "rsa_pss_rsae_sha256";
    case MBEDTLS_TLS1_3_SIG_RSA_PSS_RSAE_SHA384:  return "rsa_pss_rsae_sha384";
    case MBEDTLS_TLS1_3_SIG_RSA_PSS_RSAE_SHA512:  return "rsa_pss_rsae_sha512";

    /* EdDSA */
    case MBEDTLS_TLS1_3_SIG_ED25519:              return "ed25519";
    case MBEDTLS_TLS1_3_SIG_ED448:                return "ed448";

    default:                                       return "unknown_sig_alg";
