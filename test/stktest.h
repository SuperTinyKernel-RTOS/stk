struct MutexMock : public IMutex
{
    explicit MutexMock() : m_nesting(0), m_locked(false)
    {}

    uint32_t m_nesting;
    bool     m_locked;

    void Lock() override
    {
        if (m_nesting == 0)
            m_locked = true;

        ++m_nesting;
    }

    void Unlock() override
    {
        STK_ASSERT(m_nesting != 0);

        if (--m_nesting == 0)
            m_locked = false;
    }

    bool TryLock() override
    {
        if (m_locked)
            return false;

        Lock();
        return true;
    }
};

